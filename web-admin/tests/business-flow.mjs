import assert from 'node:assert/strict';
import process from 'node:process';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';

if (!process.env.ISOLATED_TEST_DATABASE || process.env.DB_NAME !== process.env.ISOLATED_TEST_DATABASE) throw new Error('Chạy npm run test:system trong backend để kiểm thử với database riêng.');
const base = process.env.ADMIN_URL, apiUrl = process.env.API_URL;
const call = async (path, token, method = 'GET', body) => {
  const response = await fetch(`${apiUrl}${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  const result = await response.json();
  assert.ok(response.ok, JSON.stringify(result)); return result.data;
};
const login = email => call('/auth/login', null, 'POST', { email, password: 'Parking@123' });
const resident = await login('resident1@parking.local'), manager = await login('manager1@parking.local'), guard = await login('guard1@parking.local');
const stamp = Date.now();
const area = await call('/areas', manager.accessToken, 'POST', { code: `UI-${stamp}`, name: 'Bãi kiểm thử trình duyệt', location: 'B1', capacity: 5 });
const plan = (await call('/plans', resident.accessToken)).find(p => p.vehicleType === 'MOTORBIKE' && p.status === 'ACTIVE');
const vehicle = await call('/vehicles', resident.accessToken, 'POST', { licensePlate: `UI-${stamp}`, type: 'MOTORBIKE' });
const reg = await call('/registrations', resident.accessToken, 'POST', { vehicleId: vehicle.id, planId: plan.id, areaId: area.id });
const browser = await chromium.launch(process.env.BROWSER_PATH ? { headless: true, executablePath: process.env.BROWSER_PATH } : { headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const row = () => page.getByRole('row').filter({ hasText: vehicle.licensePlate });
try {
  await page.goto(`${base}/login`, { waitUntil: 'networkidle' });
  await page.locator('input[type="email"]').fill('admin@parking.local');
  await page.locator('input[type="password"]').fill('Parking@123');
  await page.locator('button[type="submit"]').click();
  await page.waitForURL('**/dashboard');
  await page.goto(`${base}/registrations`, { waitUntil: 'networkidle' });
  await row().getByRole('button', { name: 'Duyệt', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await row().getByRole('button', { name: 'Ghi nhận tiền', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Phương thức').selectOption('BANK_TRANSFER');
  await page.getByRole('dialog').getByLabel('Mã giao dịch / chứng từ').fill(`BANK-UI-${stamp}`);
  await page.getByRole('dialog').getByRole('button', { name: 'Đã nhận đủ tiền', exact: true }).click();
  await row().getByRole('button', { name: 'Hoàn tiền', exact: true }).waitFor();
  const paid = await call(`/registrations/${reg.id}`, resident.accessToken);
  assert.equal(paid.payments.find(p => p.status === 'PAID').method, 'BANK_TRANSFER');
  assert.equal(paid.ticket.status, 'ACTIVE');
  const qr = await call(`/tickets/${paid.ticket.id}/qr`, resident.accessToken);
  const session = await call('/parking/check-in', guard.accessToken, 'POST', { qrToken: qr.token, gate: 'UI-IN', areaId: area.id, licensePlate: vehicle.licensePlate, requestId: `ui-entry-${stamp}` });
  await row().getByRole('button', { name: 'Hoàn tiền', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Đã hoàn tiền thực tế', exact: true }).click();
  await page.getByText('Không thể hoàn tiền khi xe còn trong bãi', { exact: true }).waitFor();
  await page.goto(`${base}/parking-sessions`, { waitUntil: 'networkidle' });
  await row().getByRole('button', { name: 'Xác minh xe ra', exact: true }).click();
  await page.getByRole('dialog').getByLabel('Cổng ra thực tế').fill('UI-OUT');
  await page.getByRole('dialog').getByLabel('Lý do và căn cứ đối chiếu chủ xe/camera (mất QR, vé khóa...)').fill('Đã đối chiếu chủ xe và camera cổng ra');
  await page.getByRole('dialog').getByRole('button', { name: 'Đã đối chiếu và xác nhận xe ra', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const closed = (await call('/parking/sessions', guard.accessToken)).find(s => s.id === session.id);
  assert.equal(closed.status, 'ABNORMAL'); assert.ok(closed.checkOutAt); assert.equal(closed.checkOutGate, 'UI-OUT');
  await page.goto(`${base}/registrations`, { waitUntil: 'networkidle' });
  await row().getByRole('button', { name: 'Hoàn tiền', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Đã hoàn tiền thực tế', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const refunded = await call(`/registrations/${reg.id}`, resident.accessToken);
  assert.equal(refunded.ticket.status, 'REVOKED'); assert.equal(refunded.status, 'CANCELLED');
  assert.equal(refunded.payments.find(p => p.status === 'REFUNDED').amount, paid.payments[0].amount);
  assert.equal(await row().getByRole('button', { name: 'Ghi nhận tiền', exact: true }).count(), 0);
  await mkdir('tests/artifacts', { recursive: true });
  await page.screenshot({ path: 'tests/artifacts/business-flow.png', fullPage: true });
  assert.deepEqual(errors, []);
  process.stdout.write('BUSINESS_UI_OK: duyệt → chuyển khoản → cấp vé → vào bãi → chặn hoàn tiền khi còn xe → xác minh ra → hoàn tiền và thu hồi vé.\n');
} finally { await browser.close(); }
